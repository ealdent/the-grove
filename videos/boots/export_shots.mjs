// Evaluate edit.js outside the browser and write the resolved cut list (MEDIA/shots.json) for mix.py and reports.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const MEDIA = path.resolve(process.env.MEDIA || path.join(HERE, '..', '..', 'tmp', 'boots-march'));
const ctx = { window: {} }; ctx.Object = Object; ctx.Math = Math;
vm.runInNewContext(readFileSync(path.join(HERE, 'edit.js'), 'utf8'), ctx);
const { SHOTS, END, T0 } = ctx.window;
writeFileSync(path.join(MEDIA, 'shots.json'), JSON.stringify({ T0, END, shots: SHOTS.map(s => ({ t: +s.t.toFixed(3), id: s.id, hit: s.hit, flash: s.flash || null, boom: s.boom || 0, big: s.big || null, small: s.small || null, colour: !!s.colour, date: s.date || null })) }));
// --page: the data the public page (index.html) reads: the dated cards as a ledger, and the timeline marker's track
if (process.argv.includes('--page')) {
  const NOW = ctx.window.NOW, clean = x => x.replace(/\n/g, ' ').replace(/\^/g, '');
  const ledger = [], track = [];
  for (const s of SHOTS) {
    const last = track[track.length - 1];
    if (s.d != null && (!last || last[1] !== +s.d.toFixed(3) || last[2] !== (s.date || null))) track.push([+s.t.toFixed(2), +s.d.toFixed(3), s.date || null]);
    if (!s.small || s.d == null || s.d > NOW + 0.01) continue;
    let h = s.count ? (s.count.pre || '') + s.count.to.toLocaleString('en-US') + (s.count.post || '') : s.big ? clean(s.big) : null, c = s.small;
    if (!h) { const k = c.lastIndexOf(' · '); h = k < 0 ? c : c.slice(0, k); c = k < 0 ? '' : c.slice(k + 3); }
    const prev = ledger[ledger.length - 1];
    if (prev && prev.h === h && prev.c === c) continue;
    ledger.push({ t: +s.t.toFixed(2), h, c, y: Math.floor(s.d + 1e-6) });
  }
  writeFileSync(path.join(HERE, 'ledger.js'), '// generated by `node export_shots.mjs --page` from edit.js; do not edit\nwindow.BOOTS_LEDGER = ' + JSON.stringify(ledger) + ';\nwindow.BOOTS_TRACK = ' + JSON.stringify(track) + ';\n');
  console.log('ledger', ledger.length, 'cards; track', track.length, 'points');
}
const ids = new Set(SHOTS.map(s => s.id).filter(i => i[0] !== '#'));
console.log(SHOTS.length, 'shots,', [...ids].filter(i => !i.startsWith('c:')).length, 'images,', [...ids].filter(i => i.startsWith('c:')).length, 'clips, END', END.toFixed(2));
if (process.argv.includes('--ids')) console.log([...ids].join(' '));
